"""Live MOOSE adapter for periodic elastoplastic truss specimens of the TL1 family (Mode C).

A specimen is a JSON file (schema = lattice/TL1_frozen.json of the TL1 study): bar length 'a', cell vectors L1/L2, nodes, bars
{i, j, shift, family}, families {name: {material, area, theta_deg}}, materials {name: {E, sigma_y, H}}.  prepare_workspace() creates
    <ws>/lattice/lattice_def.py      generated from the JSON (same interface as the frozen TL1 lattice module)
    <ws>/oracle/truss_oracle.py      VERBATIM copy of the frozen, validated TL1 oracle (sha256 checked; never edited)
    <ws>/oracle/mesh_TL1/, calibration_TL1.json   copied for the built-in TL1 specimen; built with MOOSE for a new specimen
Portability wrappers (runtime only, recorded here): the oracle's hard-coded conda paths are replaced at runtime by
    MOOSE executable      $YSBO_MOOSE_EXE (or config moose_exe)              -> module attribute MOOSE_EXE
    MOOSE run environment $YSBO_MOOSE_ENV_PREFIX/bin prepended to PATH (opt.) -> _moose_env
    ncdump (new meshes)   $YSBO_NCDUMP or `ncdump` on PATH                   -> _ncdump_var
Limits inherited from the frozen oracle: equal bar length for every bar (checked); serial MOOSE runs; Levin plastic-strain yield criterion."""
import hashlib, importlib.util, json, os, re, shutil, subprocess, sys
from pathlib import Path
import numpy as np
from . import _frozen as F
from .core import BaseOracle, _obs

FROZEN_ORACLE = F.TRUSS / "oracle" / "truss_oracle.py"
TL1_JSON = F.TRUSS / "lattice" / "TL1_frozen.json"

LATTICE_TEMPLATE = '''"""GENERATED by yield_surface_bo.moose_truss from {src} (sha256 {sha}).  Same interface as the frozen TL1 lattice_def module."""
import numpy as np
_S = {spec}
A_BAR = float(_S["a"]); L1 = np.array(_S["L1"], float); L2 = np.array(_S["L2"], float); NODES = np.array(_S["nodes"], float)
NODE_ROLE = _S.get("node_role", ["node"] * len(NODES)); MATERIALS = _S["materials"]
FAMILY = {{k: (v["material"], float(v["area"]), v.get("theta_deg", 0)) for k, v in _S["families"].items()}}
BLOCK_ID = {{k: i + 1 for i, k in enumerate(_S["families"])}}


def cell_area():
    return float(abs(L1[0] * L2[1] - L1[1] * L2[0]))


def bars():
    return [dict(i=int(b["i"]), j=int(b["j"]), shift=tuple(int(x) for x in b["shift"]), family=b["family"], theta_deg=b.get("theta_deg", 0)) for b in _S["bars"]]
'''


def validate_lattice(spec):
    """errors / info for a specimen JSON: equal bar length, references, periodic static stability (equilibrium-matrix rank)."""
    err = []; a = float(spec["a"]); L1, L2 = np.array(spec["L1"], float), np.array(spec["L2"], float); X = np.array(spec["nodes"], float)
    fams, mats = spec["families"], spec["materials"]; rows = []
    for k, b in enumerate(spec["bars"]):
        if b["family"] not in fams:
            err.append(f"bar {k}: unknown family {b['family']}"); continue
        if fams[b["family"]]["material"] not in mats:
            err.append(f"family {b['family']}: unknown material")
        v = X[b["j"]] + b["shift"][0] * L1 + b["shift"][1] * L2 - X[b["i"]]; ln = np.linalg.norm(v)
        if abs(ln - a) > 1e-9 * a:
            err.append(f"bar {k}: length {ln:.6g} != a = {a} (the frozen TL1 oracle requires equal bar lengths)")
        t = v / ln; s = b["shift"][0] * L1 + b["shift"][1] * L2; r = np.zeros(2 * (len(X) - 1) + 3)
        for node, sg in ((b["j"], 1.0), (b["i"], -1.0)):
            if node > 0:
                r[2 * (node - 1):2 * node] += sg * t
        r[-3:] += [t[0] * s[0], t[0] * s[1], t[1] * s[1]]; rows.append(r)
    ndof = 2 * (len(X) - 1) + 3; rank = int(np.linalg.matrix_rank(np.array(rows))) if rows else 0
    if rank < ndof:
        err.append(f"periodic truss is a mechanism: equilibrium-matrix rank {rank} < {ndof} DOF (not mechanically stable)")
    for m, p in mats.items():
        if not (p["E"] > 0 and p["sigma_y"] > 0 and p["H"] > 0):
            err.append(f"material {m}: E, sigma_y and H must be > 0 (linear hardening keeps the stress-controlled solve well posed)")
    return dict(errors=err, rank=rank, ndof=ndof, static_indeterminacy=len(rows) - ndof, n_nodes=len(X), n_bars=len(rows))


def find_moose(exe=None):
    exe = exe or os.environ.get("YSBO_MOOSE_EXE") or shutil.which("combined-opt") or shutil.which("solid_mechanics-opt")
    out = dict(exe=exe, found=False)
    if not exe:
        out["error"] = "no MOOSE executable: set YSBO_MOOSE_EXE (a MOOSE app with the solid_mechanics module, e.g. combined-opt)"; return out
    p = Path(exe)
    if not p.exists():
        out["error"] = f"{exe} does not exist"; return out
    if not os.access(p, os.X_OK):
        out["error"] = f"{exe} is not executable"; return out
    out["found"] = True; return out


def moose_version(exe, env=None, timeout=120):
    """runs `<exe> --version` (no simulation)."""
    p = subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=timeout, env=env)
    return dict(returncode=p.returncode, output=(p.stdout + p.stderr).strip()[-600:])


def _env(prefix=None):
    pre = prefix or os.environ.get("YSBO_MOOSE_ENV_PREFIX")
    e = dict(os.environ, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1")
    if pre:
        e["PATH"] = str(Path(pre) / "bin") + os.pathsep + e.get("PATH", ""); e["CONDA_PREFIX"] = str(pre)
    return e


def prepare_workspace(ws, lattice_json=None):
    """create (or reuse) a specimen workspace.  lattice_json None = the frozen TL1 specimen (mesh and calibration copied)."""
    ws = Path(ws); src = Path(lattice_json) if lattice_json else TL1_JSON; spec = json.loads(src.read_text())
    v = validate_lattice(spec)
    if v["errors"]:
        raise ValueError("incompatible truss specimen: " + "; ".join(v["errors"]))
    (ws / "lattice").mkdir(parents=True, exist_ok=True); (ws / "oracle").mkdir(parents=True, exist_ok=True)
    (ws / "lattice" / "lattice_def.py").write_text(LATTICE_TEMPLATE.format(src=src.name, sha=F.sha256(src), spec=repr(spec)))
    shutil.copyfile(src, ws / "lattice" / "specimen.json")
    dst = ws / "oracle" / "truss_oracle.py"
    if not dst.exists():
        shutil.copyfile(FROZEN_ORACLE, dst)
    if F.sha256(dst) != F.sha256(FROZEN_ORACLE):
        raise RuntimeError("workspace oracle differs from the frozen TL1 oracle")
    if lattice_json is None:                                                  # TL1: reuse the validated mesh + MOOSE calibration (no MOOSE needed to set up)
        if not (ws / "oracle" / "mesh_TL1").exists():
            shutil.copytree(F.TRUSS / "oracle" / "mesh_TL1", ws / "oracle" / "mesh_TL1")
        shutil.copyfile(F.TRUSS / "oracle" / "calibration_TL1.json", ws / "oracle" / "calibration.json")
    (ws / "workspace.json").write_text(json.dumps(dict(specimen=str(src), specimen_sha256=F.sha256(src), lattice_check=v,
                                                       oracle_sha256=F.sha256(dst), builtin_tl1=lattice_json is None), indent=1))
    return v


def load_oracle_module(ws, moose_exe=None, env_prefix=None):
    """import the workspace copy of the frozen oracle with the generated lattice and the portability wrappers applied."""
    ws = Path(ws); sys.modules.pop("lattice_def", None); sys.path.insert(0, str(ws / "lattice"))
    name = "ysbo_truss_oracle_" + hashlib.sha1(str(ws.resolve()).encode()).hexdigest()[:10]
    spec = importlib.util.spec_from_file_location(name, ws / "oracle" / "truss_oracle.py"); TO = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(TO); sys.path.remove(str(ws / "lattice"))
    TO.MOOSE_EXE = find_moose(moose_exe).get("exe") or "MOOSE_EXECUTABLE_NOT_CONFIGURED"
    TO._moose_env = lambda: _env(env_prefix)                                   # portability wrapper (runtime only)
    ncd = os.environ.get("YSBO_NCDUMP") or shutil.which("ncdump") or "ncdump"

    def _ncdump_var(path, var):                                              # same parsing as the frozen function, portable executable lookup
        txt = subprocess.run([ncd, "-v", var, str(path)], capture_output=True, text=True, check=True, env=_env(env_prefix)).stdout
        body = txt.split(f" {var} =", 1)[1].split(";")[0]; return np.array([float(x) for x in re.findall(r"[-+0-9.eE]+", body)])
    TO._ncdump_var = _ncdump_var
    return TO


class TrussMooseOracle(BaseOracle):
    """live MOOSE yield-radius measurements (one serial MOOSE run per direction) with the validated TL1 oracle numerics."""

    def __init__(self, ws, lattice_json=None, moose_exe=None, env_prefix=None, solver=None, threshold=1e-4, calibration=None):
        prepare_workspace(ws, lattice_json); self.ws = Path(ws); self.TO = load_oracle_module(ws, moose_exe, env_prefix)
        self.solver = dict(solver or {}); self.solver["threshold"] = float(threshold); self.n = 0
        calf = Path(calibration) if calibration else self.ws / "oracle" / "calibration.json"
        self.cal = json.loads(calf.read_text()) if calf.exists() else None

    def ensure_ready(self):
        if not find_moose(self.TO.MOOSE_EXE)["found"]:
            raise RuntimeError(find_moose(self.TO.MOOSE_EXE)["error"])
        self.TO.build_mesh()                                                   # TL1: copied mesh is reused; new specimen: MOOSE --mesh-only + ncdump
        if self.cal is None:                                                   # new specimen: 3 elastic MOOSE probes (Levin influence matrix + compliance)
            self.cal = self.TO.calibrate(self.ws / "calibration_probes"); (self.ws / "oracle" / "calibration.json").write_text(json.dumps(self.cal, indent=1))

    def write_input(self, d, path):
        """dry run: write the MOOSE input for direction d without running MOOSE (requires an existing mesh and calibration)."""
        sch, r1 = self.TO.schedule(d, self.cal, dict(self.TO.DEFAULTS, **self.solver)); opt = dict(self.solver, **sch)
        self.TO.write_input(d, path, C=np.asarray(self.cal["C"]), Sbar=self.cal["Sbar"], **opt); return dict(path=str(path), predicted_first_yield=r1)

    def evaluate(self, d):
        if self.n == 0:
            self.ensure_ready()
        self.n += 1; wd = self.ws / "trials" / f"t{self.n:05d}"
        while wd.exists():
            self.n += 1; wd = self.ws / "trials" / f"t{self.n:05d}"
        rec = self.TO.observe(np.asarray(d, float), wd, self.cal, **self.solver)
        ok = bool(rec.get("accepted"))
        (wd / "record.json").write_text(json.dumps(rec, indent=1, default=float))
        return _obs(d, rec.get("yield_radius"), ok, rec.get("stress_mandel"), meta=dict(workdir=str(wd), cpu_s=float(rec.get("cpu_s", 0.0)),
                                                                                    flags=";".join(rec.get("flags", []))))

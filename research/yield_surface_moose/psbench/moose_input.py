"""MOOSE input-file writer for the plane-stress periodic RVE under macroscopic stress control.

Formulation (all objects from the installed solid_mechanics module):
  * Small-strain total-Lagrangian kernels (large_kinematics = false).
  * True plane stress: out-of-plane strain `strain_zz` is an unknown field
    (ComputeLagrangianWPSStrain) whose equation is the weak condition
    int(phi * sigma_zz) = 0 (TotalLagrangianWeakPlaneStress). strain_zz uses a
    discontinuous L2_LAGRANGE FIRST basis, which has exactly as many DOFs per element
    as the default quadrature has points (4 on QUAD4, 3 on TRI3), so the weak
    condition forces sigma_zz = 0 at every quadrature point. Out-of-plane shear
    strains are identically zero and, for isotropic phases, so are sigma_xz, sigma_yz.
  * Periodic displacement fluctuations + homogenization scalar (macro gradient)
    with stress constraints on <sigma_xx>, <sigma_xy>, <sigma_yy>: the macroscopic
    stress direction is imposed exactly; no strain-path calibration is needed.
  * Matrix: isotropic elasticity + J2 radial return with linear isotropic hardening
    (IsotropicPlasticityStressUpdate); inclusion: linear elastic.
"""

import math
from pathlib import Path

SQRT2 = math.sqrt(2.0)


def _blk(name, typ, body=None, indent="  "):
    s = f"{indent}[{name}]\n{indent}  type = {typ}\n"
    for k, v in (body or {}).items():
        s += f"{indent}  {k} = {v}\n"
    return s + f"{indent}[]\n"


def write_input(path, mesh_file, spec, direction, times, stop_eqps, L=1.0,
                field_output=False, exodus=False, checkpoint=False, restart_from=None):
    """direction: unit Mandel stress direction (d_xx, d_yy, sqrt2*d_xy); the macroscopic
    stress follows sigma_M(t) = t * direction, so `t` is the Mandel stress radius (MPa).

    times: load radii; times[0] is the start (0, or ignored on restart).
    checkpoint: write a checkpoint at every step (consumed by a later restart).
    restart_from: checkpoint file base to restart the solution and material state from.
    MOOSE resets time to 0 on restart; the loading depends only on the current radius,
    so the restart continues the identical load path."""
    dxx, dyy, dm = direction
    dxy = dm / SQRT2
    has_incl = spec["inclusion"] is not None
    m, inc = spec["matrix"], spec["inclusion"]
    all_blocks = "'matrix inclusion'" if has_incl else "matrix"

    s = f"""# Auto-generated by psbench.moose_input. Plane-stress periodic RVE, stress control.
[GlobalParams]
  displacements = 'disp_x disp_y'
  large_kinematics = false
  stabilize_strain = false
  macro_gradient = hvar
  # column-major (xx, yx, zx, xy, yy, zy, xz, yz, zz); targets follow the same order
  constraint_types = 'stress none none stress stress none none none none'
  targets = 'sxx_t sxy_t syy_t'
[]

[Mesh]
  # small strain: the displaced mesh is never used
  use_displaced_mesh = false
  [file]
    type = FileMeshGenerator
    file = '{mesh_file}'
  []
  [pin]
    type = ExtraNodesetGenerator
    input = file
    coord = '0 0 0'
    new_boundary = pin
  []
[]

[Variables]
  [disp_x]
  []
  [disp_y]
  []
  [strain_zz]
    family = L2_LAGRANGE
    order = FIRST
  []
  [hvar]
    family = SCALAR
    order = THIRD
  []
[]

[Functions]
  [sxx_t]
    type = ParsedFunction
    expression = '{float(dxx):.17g}*t'
  []
  [sxy_t]
    type = ParsedFunction
    expression = '{float(dxy):.17g}*t'
  []
  [syy_t]
    type = ParsedFunction
    expression = '{float(dyy):.17g}*t'
  []
[]

[Kernels]
  [sdx]
    type = HomogenizedTotalLagrangianStressDivergence
    variable = disp_x
    component = 0
    macro_var = hvar
    out_of_plane_strain = strain_zz
  []
  [sdy]
    type = HomogenizedTotalLagrangianStressDivergence
    variable = disp_y
    component = 1
    macro_var = hvar
    out_of_plane_strain = strain_zz
  []
  [wps]
    type = TotalLagrangianWeakPlaneStress
    variable = strain_zz
  []
[]

[BCs]
  [Periodic]
    [x]
      variable = 'disp_x disp_y'
      primary = left
      secondary = right
      translation = '{L} 0 0'
    []
    [y]
      variable = 'disp_x disp_y'
      primary = bottom
      secondary = top
      translation = '0 {L} 0'
    []
  []
  # remove rigid translation; periodicity already excludes rigid rotation
  [pinx]
    type = DirichletBC
    boundary = pin
    variable = disp_x
    value = 0
  []
  [piny]
    type = DirichletBC
    boundary = pin
    variable = disp_y
    value = 0
  []
[]

[Materials]
"""
    s += _blk("C_matrix", "ComputeIsotropicElasticityTensor",
              dict(block="matrix", youngs_modulus=m["E"], poissons_ratio=m["nu"]))
    if has_incl:
        s += _blk("C_inclusion", "ComputeIsotropicElasticityTensor",
                  dict(block="inclusion", youngs_modulus=inc["E"], poissons_ratio=inc["nu"]))
    s += _blk("strain", "ComputeLagrangianWPSStrain",
              dict(out_of_plane_strain="strain_zz", homogenization_gradient_names="homogenization_gradient"))
    s += _blk("hgrad", "ComputeHomogenizedLagrangianStrain")
    s += _blk("stress_matrix", "ComputeLagrangianWrappedStress", dict(block="matrix", rotate_old_stress="false"))
    # J2 radial return with the consistent tangent (IsotropicPlasticityStressUpdate only
    # reports the elastic tangent, which stalls the Krylov solver once the matrix yields).
    s += _blk("stress_matrix_base", "ComputeMultiPlasticityStress",
              dict(block="matrix", plastic_models="j2", ep_plastic_tolerance=1e-10,
                   tangent_operator="nonlinear"))
    if has_incl:
        s += _blk("stress_inclusion", "ComputeLagrangianLinearElasticStress", dict(block="inclusion"))
    comps = dict(xx=(0, 0), yy=(1, 1), xy=(0, 1), zz=(2, 2), xz=(0, 2), yz=(1, 2))
    for c, (i, j) in comps.items():
        s += _blk(f"s{c}", "RankTwoCartesianComponent",
                  dict(rank_two_tensor="cauchy_stress", property_name=f"s{c}", index_i=i, index_j=j))
    for c in ("xx", "yy", "xy", "zz"):
        i, j = comps[c]
        s += _blk(f"e{c}", "RankTwoCartesianComponent",
                  dict(rank_two_tensor="total_strain", property_name=f"e{c}", index_i=i, index_j=j))
    s += _blk("vm", "RankTwoInvariant",
              dict(rank_two_tensor="cauchy_stress", property_name="vm", invariant="VonMisesStress"))
    s += "[]\n\n[Postprocessors]\n"

    pp = ""
    ex = "'initial timestep_end'"
    for c in ("xx", "yy", "xy", "zz"):
        pp += _blk(f"s_{c}", "ElementAverageMaterialProperty", dict(mat_prop=f"s{c}", execute_on=ex))
        pp += _blk(f"e_{c}", "ElementAverageMaterialProperty", dict(mat_prop=f"e{c}", execute_on=ex))
    # quadrature-point extremes of the out-of-plane stress components (plane-stress check)
    for c in ("zz", "xz", "yz"):
        for vt in ("max", "min"):
            pp += _blk(f"s{c}_qp_{vt}", "ElementExtremeMaterialProperty",
                       dict(mat_prop=f"s{c}", value_type=vt, execute_on=ex))
    # accumulated equivalent plastic strain (J2 internal parameter), element-averaged aux field
    pp += _blk("eqps_m_avg", "ElementAverageValue", dict(variable="eqps", block="matrix", execute_on=ex))
    pp += _blk("eqps_m_max", "ElementExtremeValue",
               dict(variable="eqps", value_type="max", block="matrix", execute_on=ex))
    pp += _blk("vm_max", "ElementExtremeMaterialProperty", dict(mat_prop="vm", value_type="max", execute_on=ex))
    pp += _blk("vm_m_max", "ElementExtremeMaterialProperty",
               dict(mat_prop="vm", value_type="max", block="matrix", execute_on=ex))
    if has_incl:
        pp += _blk("vm_i_max", "ElementExtremeMaterialProperty",
                   dict(mat_prop="vm", value_type="max", block="inclusion", execute_on=ex))
        pp += _blk("vm_i_avg", "ElementAverageMaterialProperty",
                   dict(mat_prop="vm", block="inclusion", execute_on=ex))
        for c in ("xx", "yy", "xy"):
            pp += _blk(f"s_{c}_i_avg", "ElementAverageMaterialProperty",
                       dict(mat_prop=f"s{c}", block="inclusion", execute_on=ex))
        pp += _blk("vol_i", "VolumePostprocessor", dict(block="inclusion", execute_on="initial"))
    pp += _blk("vol_m", "VolumePostprocessor", dict(block="matrix", execute_on="initial"))
    pp += _blk("nl_its", "NumNonlinearIterations", dict(execute_on="timestep_end"))
    pp += _blk("l_its", "NumLinearIterations", dict(execute_on="timestep_end"))
    s += pp + "[]\n\n"

    fields = ("vm", "sxx", "syy", "sxy", "szz") if field_output else ()
    s += "[AuxVariables]\n"
    for v in ("eqps",) + tuple(f"{v}_f" for v in fields):
        s += f"  [{v}]\n    family = MONOMIAL\n    order = CONSTANT\n  []\n"
    s += "[]\n\n[AuxKernels]\n"
    s += _blk("eqps", "MaterialStdVectorAux",
              dict(variable="eqps", property="plastic_internal_parameter", index=0, block="matrix",
                   execute_on="'initial timestep_end'"))
    for v in fields:
        s += _blk(f"{v}_f", "MaterialRealAux", dict(variable=f"{v}_f", property=v, execute_on="timestep_end"))
    s += "[]\n\n"

    if field_output:
        # element-averaged fields sampled at the final step (yield-point fields)
        s += "[VectorPostprocessors]\n"
        s += _blk("fields", "ElementValueSampler",
                  dict(variable="'eqps vm_f sxx_f syy_f sxy_f szz_f'", sort_by="id", execute_on="final"))
        if has_incl:
            s += _blk("incl_fields", "ElementValueSampler",
                      dict(variable="'vm_f sxx_f syy_f sxy_f'", block="inclusion", sort_by="id",
                           execute_on="final"))
        s += "[]\n\n"

    s += f"""[UserObjects]
  # linear isotropic hardening sigma_y(k) = sy * (1 + k / eps0) = sy + H * k with eps0 = sy / H
  [hardening]
    type = SolidMechanicsHardeningPowerRule
    value_0 = {float(m["sy"]):.10g}
    epsilon0 = {float(m["sy"] / m["H"]):.10g}
    exponent = 1
  []
  # tolerances in MPa; 1e-6 MPa is ~1e-8 of the yield stress
  [j2]
    type = SolidMechanicsPlasticJ2
    yield_strength = hardening
    yield_function_tolerance = 1e-6
    internal_constraint_tolerance = 1e-10
  []
  # stop once the matrix-averaged plastic strain passes the largest criterion needed
  [stop]
    type = Terminator
    expression = 'eqps_m_avg > {float(stop_eqps):.6g}'
    fail_mode = HARD
    execute_on = timestep_end
  []
[]

[Preconditioning]
  [smp]
    type = SMP
    full = true
  []
[]

[Executioner]
  type = Transient
  # PJFNK: the homogenization kernel's hand-coded Jacobian lacks the scalar <-> strain_zz
  # coupling blocks, so it is used only as the (LU) preconditioner of an exact matrix-free
  # Jacobian action.
  solve_type = PJFNK
  petsc_options_iname = '-pc_type -pc_factor_mat_solver_type'
  petsc_options_value = 'lu superlu_dist'
  line_search = none
  nl_rel_tol = 1e-9
  nl_abs_tol = 1e-9
  nl_max_its = 30
  l_tol = 1e-8
  l_max_its = 50
  [TimeStepper]
    type = TimeSequenceStepper
    time_sequence = '{' '.join(f'{float(t):.10g}' for t in times[1:])}'
  []
  start_time = 0
  end_time = {float(times[-1]):.10g}
[]

[Outputs]
  print_linear_residuals = false
  [csv]
    type = CSV
    file_base = '{Path(path).stem}_out'
    execute_vector_postprocessors_on = final
  []
"""
    if exodus:
        s += "  [exo]\n    type = Exodus\n    execute_on = 'final'\n  []\n"
    if checkpoint:
        s += f"  [cp]\n    type = Checkpoint\n    num_files = {len(times) + 10}\n  []\n"
    s += "[]\n"
    if restart_from:
        s += f"\n[Problem]\n  restart_file_base = '{restart_from}'\n[]\n"
    with open(path, "w") as f:
        f.write(s)
